// Analytics export (Sprint 7 #51): the dashboard and the campaign return as one branded document,
// PDF by default, also CSV and Excel, rendered by the shared reports module.

// Report handles GET /api/v1/analytics/report.
// @Summary Download the marketing report
// @Description The dashboard figures, leads per day, leads by source and the return on each campaign for the window, as a branded PDF (default), CSV or Excel file.
// @Tags Analytics
// @Produce application/pdf
// @Produce text/csv
// @Param X-Tenant-ID header string true "Tenant UUID"
// @Param days query int false "Window: 7, 30 or 90 (default 30)"
// @Param format query string false "pdf (default), csv or xlsx"
// @Success 200 {file} file
// @Failure 400 {object} httpapi.ErrorResponse
// @Security bearerAuth
// @Router /analytics/report [get]
func (h *Handler) Report(w http.ResponseWriter, r *http.Request) {
	tenantID, err := extractTenant(r)
	if err != nil {
		httpapi.Error(w, http.StatusBadRequest, "invalid_tenant", "missing X-Tenant-ID", nil)
		return
	}
	format, err := reports.ParseFormat(r.URL.Query().Get("format"))
	if err != nil {
		httpapi.Error(w, http.StatusBadRequest, "invalid_format", err.Error(), nil)
		return
	}
	days := dashboardDays(r.URL.Query().Get("days"))
	now := time.Now().UTC()
	rep, err := h.BuildReport(r.Context(), tenantID, days, now)
	if err != nil {
		h.logger.Error("report build failed", zap.String("tenant_id", tenantID.String()), zap.Error(err))
		httpapi.Error(w, http.StatusInternalServerError, "query_failed", "could not build the report", nil)
		return
	}
	body, mime, err := reports.Generate(rep, format)
	if err != nil {
		h.logger.Error("report render failed", zap.String("tenant_id", tenantID.String()), zap.Error(err))
		httpapi.Error(w, http.StatusInternalServerError, "render_failed", "could not render the report", nil)
		return
	}
	name := fmt.Sprintf("marketing-report-%s.%s", now.Format("2006-01-02"), format.Ext())
	w.Header().Set("Content-Type", mime)
	w.Header().Set("Content-Disposition", `attachment; filename="`+name+`"`)
	w.Header().Set("Content-Length", strconv.Itoa(len(body)))
	w.Header().Set("Cache-Control", "no-store")
	w.WriteHeader(http.StatusOK)
	_, _ = w.Write(body)
}

// BuildReport assembles the report model for the last days days before now.
func (h *Handler) BuildReport(ctx context.Context, tenantID uuid.UUID, days int, now time.Time) (*reports.Report, error) {
	t, err := h.db.Tenant.Get(ctx, tenantID)
	if err != nil {
		return nil, err
	}
	dash, err := h.dashboard(ctx, tenantID, days, now)
	if err != nil {
		return nil, err
	}
	since := now.AddDate(0, 0, -days)
	roi, err := ComputeROI(ctx, h.db, tenantID, since, now)
	if err != nil {
		return nil, err
	}

	cur := roi.Currency
	rep := &reports.Report{
		Title:       "Marketing report",
		Subtitle:    fmt.Sprintf("Last %d days", days),
		TenantName:  t.Name,
		PeriodFrom:  since,
		PeriodTo:    now,
		GeneratedAt: now,
		Currency:    cur,
		Footer:      "Generated by MarketFlow on " + reports.DateTime(now),
	}
	if c := shareddefaults.Str(t, "brand_primary_color"); hexColor(c) {
		rep.PrimaryColor = c
	}
	if logo := shareddefaults.Str(t, "logo_url"); strings.HasPrefix(logo, "https://") {
		rep.LogoPNG, rep.LogoType = sharedcache.FetchLogo(logo)
	}

	totals := roi.Totals
	rep.Cards = []reports.Card{
		{Label: "New leads", Value: strconv.Itoa(dash.Leads.InWindow), Sub: fmt.Sprintf("%d this week", dash.Leads.ThisWeek)},
		{Label: "Conversion rate", Value: fmt.Sprintf("%.1f%%", dash.Leads.ConversionRate), Sub: fmt.Sprintf("%d of %d leads", dash.Leads.Converted, dash.Leads.Total)},
		{Label: "Ad spend", Value: reports.Money(cur, totals.Spend), Sub: perLead(cur, totals.CostPerLead)},
		{Label: "Estimated revenue", Value: reports.Money(cur, totals.EstimatedRevenue), Sub: roiCaption(totals.ROIPercent)},
	}

	rep.Sections = append(rep.Sections, reports.Section{
		Kind: reports.SectionChart, Title: "New leads", Note: chartNote(days),
		Bars: leadBars(dash.Daily, days),
	})

	if len(dash.BySource) > 0 {
		rows := make([][]reports.Cell, 0, len(dash.BySource))
		for _, s := range dash.BySource {
			rows = append(rows, []reports.Cell{reports.Text(sourceLabel(s.Source)), reports.Text(strconv.Itoa(s.Count))})
		}
		rep.Sections = append(rep.Sections, reports.Section{
			Kind: reports.SectionTable, Title: "Leads by source",
			Columns: []reports.Column{{Header: "Source", Weight: 3}, {Header: "Leads", Weight: 1, Align: "R"}},
			Rows:    rows,
		})
	}

	if len(roi.Campaigns) > 0 {
		rows := make([][]reports.Cell, 0, len(roi.Campaigns))
		for _, c := range roi.Campaigns {
			rows = append(rows, []reports.Cell{
				reports.Text(c.Name), reports.Text(reports.Money(c.Currency, c.Spend)), reports.Text(strconv.Itoa(c.Leads)),
				reports.Text(optMoney(c.Currency, c.CostPerLead)), reports.Text(strconv.Itoa(c.WonDeals)),
				reports.Text(reports.Money(c.Currency, c.EstimatedRevenue)), reports.Text(optPercent(c.ROIPercent)),
			})
		}
		rep.Sections = append(rep.Sections, reports.Section{
			Kind: reports.SectionTable, Title: "Return on each campaign", Note: averageNote(roi),
			Columns: []reports.Column{
				{Header: "Campaign", Weight: 3}, {Header: "Spend", Weight: 1.6, Money: true}, {Header: "Leads", Weight: 0.8, Align: "R"},
				{Header: "Per lead", Weight: 1.4, Money: true}, {Header: "Won", Weight: 0.7, Align: "R"},
				{Header: "Est. revenue", Weight: 1.7, Money: true}, {Header: "Return", Weight: 1, Align: "R"},
			},
			Rows: rows,
			Total: []reports.Cell{
				reports.BoldText("Total"), reports.BoldText(reports.Money(cur, totals.Spend)), reports.BoldText(strconv.Itoa(totals.Leads)),
				reports.BoldText(optMoney(cur, totals.CostPerLead)), reports.BoldText(strconv.Itoa(totals.WonDeals)),
				reports.BoldText(reports.Money(cur, totals.EstimatedRevenue)), reports.BoldText(optPercent(totals.ROIPercent)),
			},
		})
	}

	rep.Sections = append(rep.Sections, reports.Section{
		Kind: reports.SectionKeyValue, Title: "Activity",
		Pairs: []reports.KV{
			{Label: "Chats this week", Value: strconv.Itoa(dash.ChatSessions["this_week"])},
			{Label: "Active campaigns", Value: strconv.Itoa(dash.Campaigns["active"])},
			{Label: "Meetings in the next 7 days", Value: strconv.Itoa(dash.Meetings["upcoming_week"])},
			{Label: "Leads in follow-up sequences", Value: strconv.Itoa(dash.Nurture["active_enrollments"])},
		},
	})
	return rep, nil
}

// leadBars is one bar per day up to a month, one per week (Monday start) beyond that.
func leadBars(daily []DayCount, days int) []reports.Bar {
	if days <= 31 {
		bars := make([]reports.Bar, 0, len(daily))
		for _, d := range daily {
			label := d.Day
			if t, err := time.Parse("2006-01-02", d.Day); err == nil {
				label = t.Format("02 Jan")
			}
			bars = append(bars, reports.Bar{Label: label, Value: float64(d.Count)})
		}
		return bars
	}
	var bars []reports.Bar
	for _, d := range daily {
		t, err := time.Parse("2006-01-02", d.Day)
		if err != nil {
			continue
		}
		start := t.AddDate(0, 0, -((int(t.Weekday()) + 6) % 7))
		label := "w/c " + start.Format("02 Jan")
		if n := len(bars); n > 0 && bars[n-1].Label == label {
			bars[n-1].Value += float64(d.Count)
			continue
		}
		bars = append(bars, reports.Bar{Label: label, Value: float64(d.Count)})
	}
	return bars
}

func chartNote(days int) string {
	if days <= 31 {
		return "Per day"
	}
	return "Per week, starting Monday"
}

// sourceLabel turns a lead source key into words: "meta_ads" is "Meta ads".
func sourceLabel(s string) string {
	s = strings.ReplaceAll(strings.TrimSpace(s), "_", " ")
	if s == "" {
		return "Unknown"
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func averageNote(r ROIReport) string {
	switch r.AverageFrom {
	case "setting":
		return "Estimated revenue is won deals plus converted leads without a won deal at your average sale value of " +
			reports.Money(r.Currency, r.AverageSaleValue) + "."
	case "won_deals":
		return fmt.Sprintf("Estimated revenue is won deals plus converted leads without a won deal at %s, the average of your won deals over the last %d days.",
			reports.Money(r.Currency, r.AverageSaleValue), averageSaleDays)
	default:
		return "Estimated revenue is the value of won deals. Set an average sale value in Settings to count converted leads too."
	}
}

func perLead(cur string, v *float64) string {
	if v == nil {
		return ""
	}
	return reports.Money(cur, *v) + " per lead"
}

func roiCaption(v *float64) string {
	if v == nil {
		return ""
	}
	return optPercent(v) + " return on spend"
}

func optMoney(cur string, v *float64) string {
	if v == nil {
		return "-"
	}
	return reports.Money(cur, *v)
}

// optPercent is "+150%" or "-20%"; a dash without spend.
func optPercent(v *float64) string {
	if v == nil {
		return "-"
	}
	if *v > 0 {
		return fmt.Sprintf("+%.0f%%", *v)
	}
	return fmt.Sprintf("%.0f%%", *v)
}

// hexColor accepts #rgb and #rrggbb.
func hexColor(s string) bool {
	if len(s) != 4 && len(s) != 7 || !strings.HasPrefix(s, "#") {
		return false
	}
	for _, c := range s[1:] {
		if !strings.ContainsRune("0123456789abcdefABCDEF", c) {
			return false
		}
	}
	return true
}
